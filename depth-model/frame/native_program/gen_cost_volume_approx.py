#!/usr/bin/env python3
"""Generate primary-graph cost-volume dead-command bitmaps for steps 2, 4, and 8."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GRAPH = ROOT / "recovered/primary/graph.json"
CENSUS = ROOT / "frame/native_program/census_primary.json"
OUTPUT = Path(__file__).with_name("prepared_cost_volume_approx.h")
EXPECTED_SOURCE_SHA = "dc8fcddcf4876d11f7a717ec4f111e1d3d3a40d4f3163758b590234e0b50b92b"

graph = json.loads(GRAPH.read_text())
census = json.loads(CENSUS.read_text())
if census.get("source_sha256") != EXPECTED_SOURCE_SHA:
    raise SystemExit("primary source hash changed; re-audit before regenerating")

nodes = graph["nodes"]
by_seq = {node["sequence"]: node for node in nodes}
producer = {tid: node for node in nodes for tid in node["outputs"]}
users = {}
for node in nodes:
    for tid in node["inputs"]:
        users.setdefault(tid, []).append(node["sequence"])
tensors = {tensor["id"]: tensor for tensor in graph["tensors"]}

candidates = []
for node in nodes:
    if not node["type_name"].startswith("Concat") or len(node["outputs"]) != 1:
        continue
    tensor = tensors.get(node["outputs"][0])
    if tensor and tensor["shape"]["dimensions"] == [1, 80, 64, 64]:
        candidates.append(node)
if len(candidates) != 1:
    raise SystemExit(f"expected one [1,80,64,64] concat, found {len(candidates)}")
concat = candidates[0]
if len(concat["inputs"]) != 81:
    raise SystemExit(f"expected axis plus 80 planes, found {len(concat['inputs'])} inputs")

planes = []
for index, tensor_id in enumerate(concat["inputs"][1:]):
    reshape = producer.get(tensor_id)
    conv = producer.get(reshape["inputs"][0]) if reshape and len(reshape["inputs"]) == 1 else None
    if not reshape or not reshape["type_name"].startswith("Reshape") or not conv or not conv["type_name"].startswith("ConvLayer_s1"):
        raise SystemExit(f"plane {index} is not Reshape <- ConvLayer_s1")
    if tensors[tensor_id]["shape"]["dimensions"] != [1, 1, 64, 64]:
        raise SystemExit(f"plane {index} shape changed")
    planes.append((reshape, conv))

# Build one dead closure per compile-time approximation step. The final plane
# is always retained even when it is not step-aligned.
graph_outputs = set(graph["graph_outputs"])
dead_by_step = {}
for step, expected_dead in ((2, 629), (4, 963), (8, 1142)):
    dead = set()
    for index, (reshape, conv) in enumerate(planes):
        if index % step and index < 79:
            dead.update((reshape["sequence"], conv["sequence"]))
    changed = True
    while changed:
        changed = False
        for sequence in tuple(dead):
            node = by_seq[sequence]
            for tensor_id in node["inputs"]:
                upstream = producer.get(tensor_id)
                if not upstream or upstream["sequence"] in dead:
                    continue
                if upstream["type_name"].startswith("@DmaCheckpoint"):
                    continue
                if all(tid not in graph_outputs and all(u in dead for u in users.get(tid, []))
                       for tid in upstream["outputs"]):
                    dead.add(upstream["sequence"])
                    changed = True
    if len(dead) != expected_dead:
        raise SystemExit(f"step {step}: expected {expected_dead} dead source sequences, found {len(dead)}")
    for index, (reshape, conv) in enumerate(planes):
        omitted = bool(index % step and index < 79)
        if (reshape["sequence"] in dead) != omitted or (conv["sequence"] in dead) != omitted:
            raise SystemExit(f"step {step}, plane {index} keep/omit boundary changed")
    if any(by_seq[s]["type_name"].startswith("@DmaCheckpoint") for s in dead):
        raise SystemExit(f"step {step}: control checkpoint entered dead closure")
    dead_by_step[step] = dead

word_count = (max(by_seq) + 32) // 32
sha = bytes.fromhex(EXPECTED_SOURCE_SHA)
with OUTPUT.open("w") as out:
    out.write("/* Generated by gen_cost_volume_approx.py from recovered/primary/graph.json.\n")
    out.write(" * Exact primary QDRX source SHA gates these graph-specific dead-branch maps.\n")
    out.write(" * Step 2/4/8 omit 39/59/69 interior planes; plane 79 stays as boundary.\n */\n")
    out.write("#ifndef NPRG2_PREPARED_COST_VOLUME_APPROX_H\n#define NPRG2_PREPARED_COST_VOLUME_APPROX_H\n\n")
    out.write('#include "nprg2_runtime.h"\n#include <stdint.h>\n#include <string.h>\n\n')
    out.write("#ifndef NPRG2_APPROX_COST_VOLUME_STEP\n#define NPRG2_APPROX_COST_VOLUME_STEP 0\n#endif\n\n")
    out.write("#if NPRG2_APPROX_COST_VOLUME_STEP == 2 || NPRG2_APPROX_COST_VOLUME_STEP == 4 || NPRG2_APPROX_COST_VOLUME_STEP == 8\n")
    out.write("static inline int nprg2_approx_cv_primary_program(const Nprg2Program *program) {\n")
    out.write("    static const uint8_t sha[32] = {\n")
    for at in range(0, len(sha), 16):
        out.write("        " + ",".join(f"0x{v:02x}" for v in sha[at:at+16]) + ",\n")
    out.write("    };\n    return program && !memcmp(program->source_sha256, sha, sizeof(sha));\n}\n")
    for step, dead in dead_by_step.items():
        bits = [0] * word_count
        for sequence in dead:
            bits[sequence // 32] |= 1 << (sequence % 32)
        out.write(f"static const uint32_t nprg2_approx_cv_primary_dead_{step}[{word_count}] = {{\n")
        for at in range(0, len(bits), 8):
            out.write("    " + ", ".join(f"0x{value:08x}u" for value in bits[at:at+8]) + ",\n")
        out.write("};\n")
    out.write("#if NPRG2_APPROX_COST_VOLUME_STEP == 2\n#define NPRG2_APPROX_CV_INTERPOLATED_PLANES 39u\n#define NPRG2_APPROX_CV_DEAD_TABLE nprg2_approx_cv_primary_dead_2\n")
    out.write("#elif NPRG2_APPROX_COST_VOLUME_STEP == 4\n#define NPRG2_APPROX_CV_INTERPOLATED_PLANES 59u\n#define NPRG2_APPROX_CV_DEAD_TABLE nprg2_approx_cv_primary_dead_4\n")
    out.write("#else\n#define NPRG2_APPROX_CV_INTERPOLATED_PLANES 69u\n#define NPRG2_APPROX_CV_DEAD_TABLE nprg2_approx_cv_primary_dead_8\n#endif\n")
    out.write(f"#define NPRG2_APPROX_CV_WORDS {word_count}u\n")
    out.write("static inline int nprg2_approx_cv_primary_skip_seq(uint16_t sequence) {\n")
    out.write("    uint32_t w=(uint32_t)sequence>>5; return w<NPRG2_APPROX_CV_WORDS &&\n")
    out.write("        ((NPRG2_APPROX_CV_DEAD_TABLE[w]>>(sequence&31u))&1u);\n}\n")
    out.write("#endif\n\n#ifndef NPRG2_APPROX_CV_INTERPOLATED_PLANES\n#define NPRG2_APPROX_CV_INTERPOLATED_PLANES 0u\n#endif\n\n#endif\n")
print(f"{OUTPUT}: " + ", ".join(f"step {step}: {len(dead)} dead source sequences" for step, dead in dead_by_step.items()))
