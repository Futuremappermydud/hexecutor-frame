"""Generate independent NumPy golden reference data for persistent state decode simulator test.

Simulates 5 autoregressive decode steps with:
1. HX_SHORTCONV (op 24): conv state ring persistence across steps (K=3, S_LEN=2, C=32, SiLU)
2. HX_KV_WRITE (op 26): KV cache position-indexed write persistence across steps
Emits C header: test_persistent_golden.h
"""

import sys
import numpy as np

def generate_golden():
    np.random.seed(42)

    C = 32
    K_TAPS = 3
    S_LEN = K_TAPS - 1
    MAX_TOKENS = 8
    NUM_STEPS = 5

    # Random weights and bias
    conv_w = np.random.uniform(-0.5, 0.5, size=(K_TAPS, C)).astype(np.float32)
    conv_b = np.random.uniform(-0.2, 0.2, size=(C,)).astype(np.float32)

    # Random per-step inputs
    x_conv_steps = np.random.uniform(-1.0, 1.0, size=(NUM_STEPS, C)).astype(np.float32)
    k_val_steps = np.random.uniform(-1.0, 1.0, size=(NUM_STEPS, C)).astype(np.float32)
    pos_steps = np.array([float(i) for i in range(NUM_STEPS)], dtype=np.float32)

    # Persistent buffers initialized to 0
    state_ring = np.zeros((S_LEN, C), dtype=np.float32)
    kv_cache = np.zeros((MAX_TOKENS, C), dtype=np.float32)

    golden_conv_out = np.zeros((NUM_STEPS, C), dtype=np.float32)
    golden_conv_state = np.zeros((NUM_STEPS, S_LEN, C), dtype=np.float32)
    golden_kv_cache = np.zeros((NUM_STEPS, MAX_TOKENS, C), dtype=np.float32)

    for step in range(NUM_STEPS):
        # 1. Conv step using numpy
        # Accumulate over history taps:
        acc = conv_b.astype(np.float64).copy()
        for j in range(S_LEN):
            acc += state_ring[j].astype(np.float64) * conv_w[j].astype(np.float64)
        acc += x_conv_steps[step].astype(np.float64) * conv_w[S_LEN].astype(np.float64)

        # Update state ring:
        for j in range(S_LEN - 1):
            state_ring[j] = state_ring[j + 1].copy()
        state_ring[S_LEN - 1] = x_conv_steps[step].copy()

        # SiLU activation: x / (1 + exp(-x)) in float32
        acc_f32 = acc.astype(np.float32)
        out_conv = acc_f32 / (1.0 + np.exp(-acc_f32))
        golden_conv_out[step] = out_conv
        golden_conv_state[step] = state_ring.copy()

        # 2. KV write step
        pos = int(pos_steps[step])
        kv_cache[pos] = k_val_steps[step].copy()
        golden_kv_cache[step] = kv_cache.copy()

    # Emit C header
    with open("hexecutor/examples/llm/lfm/test_persistent_golden.h", "w") as f:
        f.write("/* Auto-generated by gen_persistent_numpy_golden.py - DO NOT EDIT MANUALLY */\n")
        f.write("/* Independent NumPy reference for persistent state Hexagon simulator test. */\n\n")
        f.write("#ifndef TEST_PERSISTENT_GOLDEN_H\n")
        f.write("#define TEST_PERSISTENT_GOLDEN_H\n\n")
        f.write(f"#define GOLDEN_C {C}u\n")
        f.write(f"#define GOLDEN_K_TAPS {K_TAPS}u\n")
        f.write(f"#define GOLDEN_S_LEN {S_LEN}u\n")
        f.write(f"#define GOLDEN_MAX_TOKENS {MAX_TOKENS}u\n")
        f.write(f"#define GOLDEN_NUM_STEPS {NUM_STEPS}u\n\n")

        def write_arr1d(name, arr):
            f.write(f"static const float {name}[{len(arr)}] = {{\n")
            for i, v in enumerate(arr):
                f.write(f"    {v:.8e}f,")
                if (i + 1) % 4 == 0:
                    f.write("\n")
            if len(arr) % 4 != 0:
                f.write("\n")
            f.write("};\n\n")

        def write_arr2d(name, arr):
            d0, d1 = arr.shape
            f.write(f"static const float {name}[{d0}][{d1}] = {{\n")
            for i in range(d0):
                f.write("    { ")
                for j in range(d1):
                    f.write(f"{arr[i, j]:.8e}f, ")
                f.write("},\n")
            f.write("};\n\n")

        def write_arr3d(name, arr):
            d0, d1, d2 = arr.shape
            f.write(f"static const float {name}[{d0}][{d1}][{d2}] = {{\n")
            for i in range(d0):
                f.write("    {\n")
                for j in range(d1):
                    f.write("        { ")
                    for k in range(d2):
                        f.write(f"{arr[i, j, k]:.8e}f, ")
                    f.write("},\n")
                f.write("    },\n")
            f.write("};\n\n")

        write_arr2d("golden_conv_w", conv_w)
        write_arr1d("golden_conv_b", conv_b)
        write_arr2d("golden_x_conv_steps", x_conv_steps)
        write_arr2d("golden_k_val_steps", k_val_steps)
        write_arr1d("golden_pos_steps", pos_steps)

        write_arr2d("golden_conv_out", golden_conv_out)
        write_arr3d("golden_conv_state", golden_conv_state)
        write_arr3d("golden_kv_cache", golden_kv_cache)

        f.write("#endif /* TEST_PERSISTENT_GOLDEN_H */\n")

    print(f"Generated test_persistent_golden.h for {NUM_STEPS} steps, C={C}.")

if __name__ == "__main__":
    generate_golden()
