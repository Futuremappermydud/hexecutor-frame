#!/usr/bin/env python3
"""Emit fixed HMX code for open LLVM from a relocation-free SDK ELF object.

The native .S remains the editable source. This rejects text relocations,
retains exported labels, and records the native-source and object hashes.
"""
import argparse
import hashlib
from pathlib import Path
import struct

def encode(obj, source):
    data=obj.read_bytes()
    if data[:7]!=b'\x7fELF\x01\x01\x01' or struct.unpack_from('<H',data,18)[0]!=164:
        raise ValueError('expected 32-bit little-endian Hexagon ELF')
    shoff=struct.unpack_from('<I',data,32)[0]
    shsize,n,strings=struct.unpack_from('<HHH',data,46)
    if shsize!=40:raise ValueError('unexpected section format')
    sections=[struct.unpack_from('<10I',data,shoff+i*40) for i in range(n)]
    shstr=sections[strings];names=data[shstr[4]:shstr[4]+shstr[5]]
    def name(tab,pos):return tab[pos:tab.index(b'\0',pos)].decode()
    ti=next(i for i,s in enumerate(sections) if name(names,s[0])=='.text')
    for s in sections:
        if s[1] in (4,9) and s[7]==ti and s[5]:raise ValueError('text contains unresolved relocations')
    text=sections[ti];code=data[text[4]:text[4]+text[5]]
    if len(code)%4:raise ValueError('unaligned code')
    labels={}
    for s in sections:
        if s[1]!=2:continue
        st=sections[s[6]];tab=data[st[4]:st[4]+st[5]]
        for off in range(s[4],s[4]+s[5],s[9]):
            sn,value,_,info,_,si=struct.unpack_from('<IIIBBH',data,off)
            if si==ti and info>>4==1:
                labels.setdefault(value,[]).append(name(tab,sn))
    lines=['/* Generated by encode_hmx.py using Qualcomm Clang 19.0.07 -mv75 -mhmx.',
           f' * Native source SHA-256: {hashlib.sha256(source.read_bytes()).hexdigest()}',
           f' * Object SHA-256: {hashlib.sha256(data).hexdigest()}',f' * Regenerate after editing {source.name}. Packet bits are included. */','    .text']
    for offset in range(0,len(code),4):
        for symbol in labels.get(offset,[]):lines += [f'    .globl {symbol}',f'{symbol}:']
        lines.append(f'    .word 0x{struct.unpack_from("<I",code,offset)[0]:08x}')
    return '\n'.join(lines)+'\n'

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('object',type=Path);p.add_argument('--source',type=Path,required=True);p.add_argument('--output',type=Path,required=True)
    a=p.parse_args();a.output.write_text(encode(a.object,a.source))
