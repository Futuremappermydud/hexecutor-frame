#!/usr/bin/env python3
"""Emit C fixtures for every space-to-depth command in both resident images."""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "frame"))
from resident_image import unpack  # noqa: E402

VARIANT = "ConvLayer_SpaceToDepth_stride2.tcm@CB*2.s4"


def c_array(values: list[int]) -> str:
    return "{" + ",".join(str(v) for v in values) + "}"


def main() -> None:
    image_rows = []
    block_ids: list[int] = []
    hashes = []
    for image_no, name in enumerate(("primary", "alternate")):
        raw = (ROOT / "frame" / "build" / f"resident-{name}.qdrx").read_bytes()
        hashes.append(hashlib.sha256(raw).hexdigest())
        graph = unpack(raw)
        tensors = {t["id"]: t for t in graph["tensors"]}
        commands = [c for c in graph["commands"] if c["variant"] == VARIANT]
        for command in commands:
            source = tensors[command["inputs"][0]]
            output = tensors[command["outputs"][0]]
            ins = source["storage"]["blocks"]
            outs = output["storage"]["blocks"]
            in_start = len(block_ids)
            block_ids.extend(b["pool"] | b["offset"] for b in ins)
            out_start = len(block_ids)
            block_ids.extend(b["pool"] | b["offset"] for b in outs)
            image_rows.append((image_no, command["sequence"],
                source["shape"]["max_dimensions"], source["shape"]["padding"],
                output["shape"]["dimensions"], output["shape"]["max_dimensions"],
                output["shape"]["padding"], in_start, len(ins),
                source["storage"]["slice_offset"], out_start, len(outs),
                output["storage"]["slice_offset"]))

    lines = [
        "/* Generated by make_space_to_depth_cases.py; do not hand-edit. */",
        f"/* primary SHA-256: {hashes[0]} */",
        f"/* alternate SHA-256: {hashes[1]} */",
        "typedef struct {",
        "    uint32_t image, sequence;",
        "    int32_t in_m[4], in_p[4], out_d[4], out_m[4], out_p[4];",
        "    uint32_t in_start, in_nblocks, in_slice;",
        "    uint32_t out_start, out_nblocks, out_slice;",
        "} LayoutS2dCase;",
        f"#define LAYOUT_S2D_CASE_COUNT {len(image_rows)}u",
        f"#define LAYOUT_S2D_BLOCK_COUNT {len(block_ids)}u",
        "static const uint32_t layout_s2d_blocks[LAYOUT_S2D_BLOCK_COUNT] = {",
    ]
    for start in range(0, len(block_ids), 12):
        lines.append("    " + ",".join(f"0x{v:08x}u" for v in block_ids[start:start+12]) + ",")
    lines.append("};")
    lines.append("static const LayoutS2dCase layout_s2d_cases[LAYOUT_S2D_CASE_COUNT] = {")
    for row in image_rows:
        image, seq, im, ip, od, om, op, ib, ni, islice, ob, no, oslice = row
        lines.append("    {")
        lines.append(f"        {image}u,{seq}u,")
        lines.append(f"        {c_array(im)},{c_array(ip)},{c_array(od)},{c_array(om)},{c_array(op)},")
        lines.append(f"        {ib}u,{ni}u,{islice}u,{ob}u,{no}u,{oslice}u")
        lines.append("    },")
    lines.extend(["};", ""])
    target = ROOT / "frame" / "layout_audit" / "space_to_depth_cases.h"
    target.write_text("\n".join(lines))
    print(f"wrote {target} cases={len(image_rows)} encoded_blocks={len(block_ids)}")
    print(f"primary sha256={hashes[0]}")
    print(f"alternate sha256={hashes[1]}")


if __name__ == "__main__":
    main()
